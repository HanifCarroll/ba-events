#!/bin/sh
set -eu
# This script never reads .env or connects to the hosted database.
intake_test_container="ba-events-intake-test-$$"
trap 'docker rm -f "$intake_test_container" >/dev/null 2>&1 || true' EXIT INT TERM
docker run --detach --rm --name "$intake_test_container" -e POSTGRES_PASSWORD=synthetic-local-only pgvector/pgvector:pg16 >/dev/null
intake_attempt=0
until docker exec "$intake_test_container" pg_isready -U postgres >/dev/null 2>&1; do
  intake_attempt=$((intake_attempt + 1))
  test "$intake_attempt" -lt 30
  sleep 1
done
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/tests/fixtures/intake-schema.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261025205334_instagram_intake.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261113220000_instagram_incremental_collection.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261114190000_instagram_wider_watchlist.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20260105000002_add_find_similar_venue.sql
# Applied twice: production migrations are run by hand and a retry must succeed.
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261115120000_intake_similar_venues.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261115120000_intake_similar_venues.sql
# Applied twice: production migrations are run by hand and a retry must succeed.
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261116120000_hidden_location_has_no_venue.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261116120000_hidden_location_has_no_venue.sql
# Applied twice: production migrations are run by hand and a retry must succeed.
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261116180000_venue_name_matching.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/migrations/20261116180000_venue_name_matching.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/tests/instagram-intake.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/tests/instagram-intake-venues.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/tests/hidden-location.sql
docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 < supabase/tests/venue-matching.sql
# The duplicate merge, generated by the same code as scripts/venue-duplicates.ts sql, on a synthetic fixture.
intake_psql() { docker exec -i "$intake_test_container" psql -U postgres -v ON_ERROR_STOP=1 -q "$@"; }
# Every row the merge may touch, in a stable order, to compare after the undo.
intake_state() { intake_psql -tA -c "select jsonb_agg(to_jsonb(v) - 'updated_at' order by id) from public.venues v" \
  -c "select jsonb_agg(jsonb_build_object('id',id,'venue_id',venue_id,'name',name) order by id) from public.events" \
  -c "select jsonb_agg(to_jsonb(q) - 'updated_at' order by id) from public.venue_review_queue q" \
  -c "select jsonb_agg(payload order by id) from public.intake_candidates" \
  -c "select jsonb_agg(payload order by candidate_id, revision) from public.intake_candidate_revisions" \
  -c "select jsonb_agg(payload order by id) from public.intake_plans" \
  -c "select jsonb_agg(to_jsonb(d) order by id) from public.dismissed_venue_duplicates d"; }
bun supabase/tests/venue-merge.ts fixture | intake_psql
bun supabase/tests/venue-merge.ts merge > "${TMPDIR:-/tmp}/$intake_test_container-merge.sql"
bun supabase/tests/venue-merge.ts undo > "${TMPDIR:-/tmp}/$intake_test_container-undo.sql"
trap 'docker rm -f "$intake_test_container" >/dev/null 2>&1 || true; rm -f "${TMPDIR:-/tmp}/$intake_test_container"-*.sql' EXIT INT TERM
# A source address corrected after the plan: the merge must refuse and change nothing.
intake_psql -c "update public.venues set address = 'Calle Otra 999' where id = '00000000-0000-4000-8000-000000000002'"
if intake_psql < "${TMPDIR:-/tmp}/$intake_test_container-merge.sql" 2>/dev/null; then echo 'FAIL: merge ran on a venue changed since the plan'; exit 1; fi
intake_psql -c "update public.venues set address = null where id = '00000000-0000-4000-8000-000000000002'"
# A reference added after the plan (a new scrape event on a source), then the real run.
intake_psql -c "insert into public.events(id,name,starts_at,source,venue_id) values('00000000-0000-4000-8000-000000000105','Nuevo',now() + interval '2 days','meetup','00000000-0000-4000-8000-000000000001')"
before=$(intake_state)
intake_psql < "${TMPDIR:-/tmp}/$intake_test_container-merge.sql"
intake_psql < supabase/tests/venue-merge.sql
intake_psql < "${TMPDIR:-/tmp}/$intake_test_container-undo.sql"
# updated_at of rows that were changed then restored moves on (their triggers); the saved values are in the backup.
after=$(intake_state)
test "$after" = "$before" || { echo 'FAIL: undo did not restore the pre-merge rows'; echo "$before"; echo "$after"; exit 1; }
# Deleted venues come back with every column as saved, updated_at included.
test "$(intake_psql -tA -c "select updated_at::date from public.venues where id = '00000000-0000-4000-8000-000000000001'")" = 2026-02-01 \
  || { echo 'FAIL: restored venue lost its updated_at'; exit 1; }
echo 'PASS: undo.sql restores every venue column and reference the merge changed'
