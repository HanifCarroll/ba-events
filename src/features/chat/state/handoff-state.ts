/**
 * Pure (plain TypeScript, no Svelte runes, no feature-module imports) first
 * message handoff and per-conversation scroll memory.
 *
 * Extracted from `ChatState` so the handoff/scroll contract can be unit-tested
 * in any runner (Bun, Vitest) without pulling in the Svelte runtime or SvelteKit
 * virtual modules that `chat.svelte.ts` transitively imports. `ChatState`
 * inherits from this base class, so these are the exact production methods.
 */

/**
 * A first message handed from one ChatContainer instance to the next.
 *
 * When a message is submitted from the home screen there is no conversation
 * yet, and creating one navigates to /chat/{id} — which remounts
 * ChatContainer. Sending from the old instance would stream the assistant
 * response into an unmounted component, so the message is parked here (the
 * state survives the remount) and the new instance sends it instead.
 */
export interface PendingFirstMessage {
	content: string
	eventId?: string
	/**
	 * Unique id for this handoff, generated by the submitting instance and
	 * carried across the remount. Scopes every handoff performance mark, so
	 * the instance that streams can read exactly this handoff's phases and a
	 * missing phase stays missing (never borrows an earlier handoff's mark).
	 */
	handoffId: string
}

export class HandoffState {
	protected pendingFirstMessage: PendingFirstMessage | null = null
	protected conversationScrollPositions = new Map<string, number>()

	setPendingFirstMessage(message: PendingFirstMessage): void {
		this.pendingFirstMessage = message
	}

	/** Read the parked first message WITHOUT clearing it (idempotent). */
	peekPendingFirstMessage(): PendingFirstMessage | null {
		return this.pendingFirstMessage
	}

	/** Read and clear the parked first message. One-shot — second call returns null. */
	takePendingFirstMessage(): PendingFirstMessage | null {
		const message = this.pendingFirstMessage
		this.pendingFirstMessage = null
		return message
	}

	/** Remember the internal chat scroller position while navigating away. */
	saveConversationScrollPosition(conversationId: string, scrollTop: number): void {
		this.conversationScrollPositions.set(conversationId, Math.max(0, scrollTop))
	}

	/** Read a previously remembered position for this conversation. */
	getConversationScrollPosition(conversationId: string): number | null {
		return this.conversationScrollPositions.get(conversationId) ?? null
	}
}
